/**
 * 把一个时刻对齐到**导出会真正渲到的那一批帧**上。
 *
 * 导出是一帧一帧推的:第 i 帧的时刻就是 i/fps,中间的时刻根本不存在。所以「一张卡什么时候
 * 挂载」在导出里只能是某个 i/fps,而不是 `start - LEAD` 这种连续值。预览如果按连续值挂载,
 * 卡片的时间原点就和成片差不到一帧 —— 对「挂载即播」的卡(绝大多数)来说,这一小段偏差
 * 落在进场动画最陡的那一段上,画面上是看得见的。
 *
 * 实测(mu-circular-progress,1.2s easeOut cubic,入点 1.0s,30fps,同一个 t=1.0):
 * 导出 6%,对齐前的预览 9%,对齐后 6% —— 之后逐帧相同。
 */

/**
 * 第一个**不早于** sec 的帧时刻。
 *
 * ⚠ 那个 1e-6 不是凑数:`2.0 * 30` 在浮点里是 60.00000000000001,直接 ceil 会把一个
 * 本来就在帧格上的时刻推到下一帧去 —— 于是「整秒入点」的卡全体晚挂一帧,而这正是
 * 最常见的入点。容差取一微秒:比任何真实帧长小四个数量级,又远大于这里的浮点误差。
 */
export function onFrameGrid(sec: number, fps: number): number {
  const f = Math.max(1, fps);
  const n = Math.ceil(sec * f - 1e-6);
  // n 为 0 时 n/f 是 -0,而 -0 !== 0 会让「原样不动」这类比较莫名其妙地不成立
  return n === 0 ? 0 : n / f;
}

/**
 * sec 落在**第几帧**上,返回那一帧的时刻。
 *
 * 和 `onFrameGrid` 是一对,方向相反:那个回答「什么时候挂载」(第一个不早于它的帧),
 * 这个回答「这一刻画面上是哪一帧」—— 成片里第 i 帧覆盖 [i/fps, (i+1)/fps),所以往下取整。
 *
 * 播放头用它:成片是 fps 帧的,预览却按显示器刷新率推连续时间,于是预览停在了成片里
 * **根本不存在的时刻**上。差的不到一帧,但 3D 那边显示的是烘好的整帧,两个视图一对比就露馅。
 *
 * ⚠ 容差的方向和 onFrameGrid 相反:`29/30 * 30` 在浮点里是 28.999999999999996,
 * 直接 floor 会退回第 28 帧 —— 帧格上的时刻反而被判到上一帧去。
 */
export function atFrameGrid(sec: number, fps: number): number {
  const f = Math.max(1, fps);
  const n = Math.floor(sec * f + 1e-6);
  return n <= 0 ? 0 : n / f;
}
